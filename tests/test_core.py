"""Conformance of the Python port against the frozen JavaScript reading kernel.

tests/conformance.json is generated by tools/dump_conformance.mjs, which imports
the SHIPPED client.js from the dsh-novel-wallpaper plugin through its own module
loader and records what it produces. This test asserts exact equality - chapter
count, every title, every start/end offset, and a SHA-256 of every chapter's text.
Never "roughly equal": an off-by-one in a chapter boundary is a real bug that
"the titles look right" would hide.

The corpus is deliberately astral-free (the dumper warns if it is not), because JS
indexes by UTF-16 unit while Python indexes by code point; they only agree when no
character needs a surrogate pair. The SHA-256 of each chapter's text is the real
invariant and would catch a divergence even if that assumption were ever broken.

    py -3.12 -m unittest discover -s tests -t .
"""

