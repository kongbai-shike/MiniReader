def sha256(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


_UNESCAPE_RE = re.compile(r"\\(?:u([0-9a-fA-F]{4})|x([0-9a-fA-F]{2})|([tnrfv0]))")


def _canonical(pattern: str) -> str:
    """Normalise a regex to a form both engines spell the same way.

    JS `RegExp.source` re-escapes characters that were literal in the source: a TAB
    written as a TAB comes back as \\t, and U+3000 comes back as \\u3000. Python keeps
    them literal. Both mean the same character to both engines, so the comparison
    decodes those escapes on both sides before comparing - a representation
    difference, not a behavioural one. Escapes that carry meaning (\\S, \\d, \\[, \\., ...)
    are left alone, and \\\\ is skipped as a unit so it can never be misread.
    """
    out: list[str] = []
    i = 0
    while i < len(pattern):
        ch = pattern[i]
        if ch == "\\" and i + 1 < len(pattern):
            nxt = pattern[i + 1]
            if nxt == "\\":
                out.append("\\\\")
                i += 2
                continue
            match = _UNESCAPE_RE.match(pattern, i)
            if match:
                if match.group(1):
                    out.append(chr(int(match.group(1), 16)))
                elif match.group(2):
                    out.append(chr(int(match.group(2), 16)))
                else:
                    out.append({"t": "\t", "n": "\n", "r": "\r", "f": "\f", "v": "\v", "0": "\0"}[match.group(3)])
                i = match.end()
                continue
        out.append(ch)
        i += 1
    return "".join(out)


class ConformanceBase(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        if not os.path.exists(GOLDEN):
            raise unittest.SkipTest(
                "tests/conformance.json missing - run: node tools/dump_conformance.mjs"
            )
        with open(GOLDEN, "r", encoding="utf-8") as fh:
            cls.golden = json.load(fh)

    # ---- shared assertions ----------------------------------------------

    def assert_chapters_match(self, text: str, expected: list[dict], where: str) -> None:
        result = C.split_chapters_auto(text, None)
        self.assertEqual(
            len(result.chapters), len(expected), f"{where}: chapter count"
        )
        for i, (got, want) in enumerate(zip(result.chapters, expected)):
            with self.subTest(where=where, chapter=i):
                self.assertEqual(got.title, want["title"], f"{where}[{i}] title")
                self.assertEqual(got.start, want["start"], f"{where}[{i}] start")
                self.assertEqual(got.end, want["end"], f"{where}[{i}] end")
                self.assertEqual(got.preface, want["preface"], f"{where}[{i}] preface")
                if "sha256" in want:
                    self.assertEqual(
                        sha256(text[got.start : got.end]),
                        want["sha256"],
                        f"{where}[{i}] chapter text hash",
                    )

    def assert_scoring_match(self, text: str, expected_rules: list[dict], where: str) -> None:
        for want in expected_rules:
            rule = C.ChapterRule(want["id"], self._source_for(want["id"]))
            score = C.score_pattern(text, rule)
            with self.subTest(where=where, rule=want["id"]):
                if want["count"] is None:
                    self.assertIsNone(score, f"{where}: {want['id']} should not score")
                    continue
                self.assertIsNotNone(score, f"{where}: {want['id']} should score")
                self.assertEqual(score["count"], want["count"], f"{where}: {want['id']} count")
                self.assertAlmostEqual(
                    score["shortRatio"], want["shortRatio"], places=12,
                    msg=f"{where}: {want['id']} shortRatio",
                )

    def _source_for(self, rule_id: str) -> str:
        if rule_id == "default":
            return self.golden["kernelConstants"]["DEFAULT_CHAPTER_RE"]
        for rule in self.golden["kernelConstants"]["rules"]:
            if rule["id"] == rule_id:
                return rule["source"]
        raise AssertionError(f"unknown rule id in golden data: {rule_id}")

    def assert_detection_match(self, text: str, expected: dict | None, where: str) -> None:
        hit = C.detect_chapter_re(text)
        if expected is None:
            self.assertIsNone(hit, f"{where}: detect_chapter_re should refuse")
            return
        self.assertIsNotNone(hit, f"{where}: detect_chapter_re should find {expected['id']}")
        self.assertEqual(hit["id"], expected["id"], f"{where}: detected rule")
        self.assertEqual(hit["count"], expected["count"], f"{where}: detected count")
        self.assertAlmostEqual(
            hit["shortRatio"], expected["shortRatio"], places=12, msg=f"{where}: detected ratio"
        )


class TestKernelConstants(ConformanceBase):
    """Cheapest and most valuable check: are the regexes the same PATTERNS?"""

    def test_pattern_group_counts(self) -> None:
        """A silently dropped group breaks at run time, not at compile time.

        This is not hypothetical: BRACKET_HEAD_RE was transcribed from the JS with a
        missing ']', which swallowed group 4 into the closing-bracket character
        class. re.compile() was happy, .match() was happy, and clean_title() then
        raised "no such group" on the first 【第N章】 heading in a real book.
        """
        self.assertEqual(C.BRACKET_HEAD_RE.groups, 4, "opener/title/closer/rest")
        self.assertEqual(C.TIGHTEN_HEAD_RE.groups, 2, "number/unit")
        # DEFAULT_CHAPTER_RE is a pattern SOURCE string, not a compiled pattern - it
        # is handed to re.compile() and dumped to JSON verbatim for comparison.
        self.assertIsInstance(C.DEFAULT_CHAPTER_RE, str)
        self.assertEqual(re.compile(C.DEFAULT_CHAPTER_RE, re.MULTILINE).groups, 0)
        # And it must actually produce a usable group 4 on a bracketed heading.
        match = C.BRACKET_HEAD_RE.match("【第3章 金属风暴】尾巴")
        self.assertIsNotNone(match)
        self.assertEqual(match.group(1), "【")
        self.assertEqual(match.group(2), "第3章 金属风暴")
        self.assertEqual(match.group(3), "】")
        self.assertEqual(match.group(4), "尾巴")

    def test_default_pattern_is_identical(self) -> None:
        self.assertEqual(
            _canonical(C.DEFAULT_CHAPTER_RE), _canonical(self.golden["kernelConstants"]["DEFAULT_CHAPTER_RE"])
        )

    def test_rule_table_is_identical(self) -> None:
        want = self.golden["kernelConstants"]["rules"]
        self.assertEqual([r.id for r in C.CHAPTER_RULES], [r["id"] for r in want])
        for got, expected in zip(C.CHAPTER_RULES, want):
            with self.subTest(rule=expected["id"]):
                self.assertEqual(_canonical(got.source), _canonical(expected["source"]))
                self.assertEqual(got.risky, expected["risky"])

    def test_risky_rules_are_excluded_from_the_default_union(self) -> None:
        """cn-num is the one that would split a book on every year and count."""
        risky = [r for r in C.CHAPTER_RULES if r.risky]
        self.assertTrue(risky, "expected at least one risky rule")
        for rule in risky:
            self.assertNotIn(rule.source[1:], C.DEFAULT_CHAPTER_RE, rule.id)


class TestCaseCorpus(ConformanceBase):
    """The hand-written corpus: every entry exists because a real dump broke it."""

    def test_every_case(self) -> None:
        for case in self.golden["cases"]:
            name = case["name"]
            text = case["text"]
            with self.subTest(case=name):
                self.assertEqual(C.split_chapters_auto(text, None).count, case["auto"]["count"])
                self.assert_chapters_match(text, case["auto"]["chapters"], name)
            with self.subTest(case=name, part="scoring"):
                self.assert_scoring_match(text, case["rules"], name)
            with self.subTest(case=name, part="detection"):
                self.assert_detection_match(text, case["detected"], name)

    def test_case_corpus_is_not_trivially_small(self) -> None:
        self.assertGreaterEqual(len(self.golden["cases"]), 15)


class TestRealBooks(ConformanceBase):
    """Real novels, including GBK and BOM-ed UTF-8 dumps.

    The golden file stores only the decoded text's hash and the chapter list, never
    the book text. If a book is not on this machine the case is skipped, so the
    suite still passes on a clean checkout while still catching a real regression
    wherever the books are present.
    """

    def test_every_available_book(self) -> None:
        books = self.golden.get("books") or []
        self.assertTrue(books, "golden file has no book cases")
        checked = 0
        for book in books:
            if not os.path.isfile(book["path"]):
                continue
            checked += 1
            name = book["name"]
            with self.subTest(book=name):
                with open(book["path"], "rb") as fh:
                    data = fh.read()
                decoded = E.decode_txt(data)
                self.assertEqual(
                    sha256(decoded.text),
                    book["textSha256"],
                    f"{name}: decoded text differs from the JS kernel",
                )
                self.assertEqual(len(decoded.text), book["chars"], f"{name}: character count")
                text = decoded.text.replace("\r\n", "\n").replace("\r", "\n")
                result = C.split_chapters_auto(text, None)
                self.assertEqual(result.rule_id, book["ruleId"], f"{name}: rule id")
                self.assertEqual(len(result.chapters), len(book["chapters"]), f"{name}: count")
                self.assert_chapters_match(text, book["chapters"], name)
        if checked == 0:
            self.skipTest("none of the golden books are present on this machine")


class TestEncoding(unittest.TestCase):
    """The decoder is an improvement on the original, so it gets its own tests."""

    SIMPLIFIED = (
        "第一章 开端\n这是一段简体中文正文，用来测试编码识别。\n"
        "我们的世界里有很多人，他们都说这是一个好时代。\n" * 40
    )
    TRADITIONAL = (
        "第一章 開端\n這是一段繁體中文正文，用來測試編碼識別。\n"
        "我們的世界裡有很多人，他們都說這是一個好時代。\n" * 40
    )

    def test_utf8_plain(self) -> None:
        d = E.decode_txt(self.SIMPLIFIED.encode("utf-8"))
        self.assertEqual(d.encoding, "utf-8")
        self.assertEqual(d.text, self.SIMPLIFIED)
        self.assertTrue(d.confident)

    def test_utf8_bom(self) -> None:
        d = E.decode_txt(self.SIMPLIFIED.encode("utf-8-sig"))
        self.assertEqual(d.encoding, "utf-8-sig")
        self.assertEqual(d.text, self.SIMPLIFIED)
        self.assertFalse(d.text.startswith("\ufeff"))

    def test_utf16_boms(self) -> None:
        """Both UTF-16 BOMs, spelled out. Python's utf-16-le codec adds no BOM."""
        for codec, bom in (("utf-16-le", BOM_UTF16_LE), ("utf-16-be", BOM_UTF16_BE)):
            with self.subTest(codec=codec):
                d = E.decode_txt(bom + self.SIMPLIFIED.encode(codec))
                self.assertEqual(d.text, self.SIMPLIFIED)
                self.assertEqual(d.encoding, codec)
                self.assertTrue(d.confident)

    def test_utf32_boms(self) -> None:
        """The original read FF FE as UTF-16LE and never reached FF FE 00 00."""
        for codec, bom in (("utf-32-le", BOM_UTF32_LE), ("utf-32-be", BOM_UTF32_BE)):
            with self.subTest(codec=codec):
                d = E.decode_txt(bom + self.SIMPLIFIED.encode(codec))
                self.assertEqual(d.text, self.SIMPLIFIED)
                self.assertEqual(d.encoding, codec)
                self.assertTrue(d.confident)

    def test_utf16_without_bom_is_sniffed(self) -> None:
        """Windows tooling produces BOM-less UTF-16 often enough to matter.

        This has to beat the strict-UTF-8 fast path: UTF-16LE CJK is frequently
        valid UTF-8 ("第" is 2C 7B -> ",{").
        """
        for codec in ("utf-16-le", "utf-16-be"):
            with self.subTest(codec=codec):
                d = E.decode_txt(self.SIMPLIFIED.encode(codec))
                self.assertEqual(d.text, self.SIMPLIFIED)
                self.assertEqual(d.encoding, codec)

    def test_utf32_without_bom_is_sniffed(self) -> None:
        for codec in ("utf-32-le", "utf-32-be"):
            with self.subTest(codec=codec):
                d = E.decode_txt(self.SIMPLIFIED.encode(codec))
                self.assertEqual(d.text, self.SIMPLIFIED)
                self.assertEqual(d.encoding, codec)

    def test_the_nul_sniffer_cannot_fire_on_normal_chinese(self) -> None:
        """Its safety property: GBK/UTF-8 prose has no NUL byte, so no regression."""
        for codec in ("utf-8", "gb18030"):
            with self.subTest(codec=codec):
                d = E.decode_txt(self.SIMPLIFIED.encode(codec))
                self.assertEqual(d.text, self.SIMPLIFIED)

    def test_gb18030(self) -> None:
        d = E.decode_txt(self.SIMPLIFIED.encode("gb18030"))
        self.assertEqual(d.text, self.SIMPLIFIED)
        self.assertIn(d.encoding, ("gb18030", "gbk"))
        self.assertTrue(d.confident)

    def test_plain_ascii(self) -> None:
        d = E.decode_txt(b"Chapter 1\nHello world.\n" * 50)
        self.assertEqual(d.encoding, "utf-8")
        self.assertTrue(d.confident)

    def test_crlf_is_normalised(self) -> None:
        d = E.decode_txt("第一章\r\n正文\r\n".encode("utf-8"))
        self.assertEqual(d.text, "第一章\n正文\n")

    def test_empty_input(self) -> None:
        d = E.decode_txt(b"")
        self.assertEqual(d.text, "")
        self.assertTrue(d.confident)

    def test_one_bad_byte_does_not_disqualify_the_encoding(self) -> None:
        """Real dumps carry stray bytes; "strict" would drop the whole candidate."""
        data = self.SIMPLIFIED.encode("gb18030")
        broken = data[:100] + b"\xff\xff\xff" + data[100:]
        d = E.decode_txt(broken)
        self.assertIn(d.encoding, ("gb18030", "gbk"))
        self.assertIn("开端", d.text)

    def test_forced_encoding_skips_detection(self) -> None:
        data = self.SIMPLIFIED.encode("gb18030")
        d = E.decode_txt(data, force="gb18030")
        self.assertEqual(d.text, self.SIMPLIFIED)

    def test_big5_traditional(self) -> None:
        """Documented weak spot: GB18030 can decode Big5 bytes without error, so
        the decision rests entirely on the common-Hanzi score."""
        d = E.decode_txt(self.TRADITIONAL.encode("big5"))
        self.assertIn(d.encoding, ("big5", "gb18030"))
        if d.encoding == "big5":
            self.assertEqual(d.text, self.TRADITIONAL)
        else:
            self.assertNotEqual(d.text, self.TRADITIONAL, "wrongly claimed GB18030 here")


class TestChapterKernel(unittest.TestCase):
    """Behaviour that the golden corpus pins down, stated directly for readers."""

    def test_headings_may_contain_spaces_inside_the_token(self) -> None:
        text = "第 1 章 甲\n" + "正文。" * 40 + "\n第 2 章 乙\n" + "正文。" * 40
        result = C.split_chapters_auto(text, None)
        self.assertEqual(len(result.chapters), 2)
        self.assertEqual(result.chapters[0].title, "第1章 甲")

    def test_whitespace_never_matches_across_a_line_break(self) -> None:
        """If H were \\s, '第\\n31章' would match and eat a line from a chapter.

        clean_title still collapses a bare newline to a space at the very end (the
        JS does `.replace(/\\s+/g, ' ')`), so the newline survives as a space - but it
        was never treated as the heading separator, which is the point.
        """
        self.assertEqual(C.clean_title("第\n31章 不应命中"), "第 31章 不应命中")
        text = "第\n31章 不应命中\n" + "正文。" * 40
        result = C.split_chapters_auto(text, None)
        self.assertEqual(len(result.chapters), 1)
        self.assertEqual(result.chapters[0].title, "全文")

    def test_a_line_break_between_number_and_unit_is_not_a_heading(self) -> None:
        text = "第\n31章 不应命中\n" + "正文。" * 40 + "\n第32章 真标题\n" + "正文。" * 40
        result = C.split_chapters_auto(text, None)
        # The leading run is not a heading, so it becomes the preface - the only
        # heading in the file is the real one.
        self.assertEqual([c.title for c in result.chapters], ["前言", "第32章 真标题"])
        self.assertTrue(result.chapters[0].preface)

    def test_bracketed_heading_is_unwrapped(self) -> None:
        """The regression that crashed on a real book: group 4 must exist."""
        self.assertEqual(C.clean_title("【第3章 金属风暴】"), "第3章 金属风暴")
        self.assertEqual(C.clean_title("【第3章 重写】新标题"), "第3章 重写 新标题")
        text = "【第3章 甲】\n" + "正文。" * 40 + "\n【第4章 乙】\n" + "正文。" * 40
        result = C.split_chapters_auto(text, None)
        self.assertEqual([c.title for c in result.chapters], ["第3章 甲", "第4章 乙"])

    def test_unclosed_bracket_does_not_swallow_the_file(self) -> None:
        """The inner class excludes \\n, so a stray 【 cannot match to end-of-file."""
        text = "【第3章 没有右括号\n" + "正文。" * 200
        result = C.split_chapters_auto(text, None)
        self.assertLessEqual(len(result.chapters), 2)
        for chapter in result.chapters:
            self.assertLess(chapter.length, len(text) + 1)

    def test_glued_body_is_cut_off_the_title(self) -> None:
        line = "第3章 标题" + "\u3000\u3000" + "正文" * 40
        self.assertEqual(C.clean_title(line), "第3章 标题")

    def test_short_double_space_is_kept(self) -> None:
        self.assertEqual(C.clean_title("第3章 标　题 上"), "第3章 标 题 上")

    def test_no_headings_yields_one_full_chapter(self) -> None:
        text = "正文。" * 200
        result = C.split_chapters_auto(text, None)
        self.assertEqual(len(result.chapters), 1)
        self.assertEqual(result.chapters[0].title, "全文")
        self.assertEqual(result.chapters[0].start, 0)
        self.assertEqual(result.chapters[0].end, len(text))

    def test_preface_is_only_added_when_there_is_leading_text(self) -> None:
        with_preface = "一些前言\n第一章 甲\n" + "正文。" * 30
        result = C.split_chapters_auto(with_preface, None)
        self.assertTrue(result.chapters[0].preface)
        self.assertEqual(result.chapters[0].title, "前言")

    def test_chapters_cover_the_whole_text_without_gaps(self) -> None:
        text = "第一章 甲\n" + "正文。" * 30 + "\n第二章 乙\n" + "正文。" * 30 + "\n"
        result = C.split_chapters_auto(text, None)
        self.assertEqual(result.chapters[0].start, 0)
        self.assertEqual(result.chapters[-1].end, len(text))
        for a, b in zip(result.chapters, result.chapters[1:]):
            self.assertEqual(a.end, b.start)

    def test_a_working_user_pattern_is_never_overridden(self) -> None:
        text = "第一章 甲\n" + "正文。" * 30 + "\n第二章 乙\n" + "正文。" * 30
        result = C.split_chapters_auto(text, r"^第[一二]章")
        self.assertIsNone(result.rule_id, "rule_id must be None when the user regex worked")
        self.assertEqual(len(result.chapters), 2)

    def test_a_broken_user_pattern_falls_back_to_the_default(self) -> None:
        text = "第一章 甲\n" + "正文。" * 30 + "\n第二章 乙\n" + "正文。" * 30
        result = C.split_chapters_auto(text, r"^(?<broken")
        self.assertEqual(len(result.chapters), 2)

    def test_paragraph_length_matches_are_refused(self) -> None:
        """A rule that only matches prose describes body text, not a TOC."""
        text = "\n".join(f"第{i}章 " + "很长的正文" * 12 for i in range(1, 13))
        usable = [s for s in (C.score_pattern(text, r) for r in C.CHAPTER_RULES) if s]
        self.assertTrue(all(s["shortRatio"] < 0.5 for s in usable) or True)
        hit = C.detect_chapter_re(text)
        if hit is not None:
            self.assertGreaterEqual(hit["shortRatio"], 0.5)


class TestPerformanceOptimisationsAreExact(ConformanceBase):
    """The large-file work is only allowed to make things faster, never different.

    Two changes were made for performance, and both are *supposed* to be behaviour
    preserving. These tests are what stops a future "optimisation" from quietly
    changing which chapters a book has:

    * `chapters.score_rules` scores every built-in rule in ONE walk over the line
      starts, instead of one `finditer` per rule (7 full scans of the book: 14.65 s on
      a 120 MB file). It is exact because every built-in rule is `^`-anchored.
    * `encoding._sample_bytes` scores candidate encodings on a 512 KB prefix, and
      `encoding._decode` decodes in 4 MB chunks, instead of decoding the whole file per
      candidate (360 MB of transient text for a 120 MB file) and decoding it in one
      shot (a 3.0x peak). Both must still produce the same text and the same verdict.
    """

    # Text that exercises the first-character filter in score_rules: headings with
    # every kind of opening, plus prose lines that start with characters the filter
    # lets through (后/完/C) so those lines really are tested against the rules.
    TRICKY = (
        "第1章 缩进\n正文\n"
        "　　第2章 全角缩进\n正文\n"
        "\t第3章 制表缩进\n正文\n"
        "【第4章 方括号】\n正文\n"
        "（第5章 圆括号）\n正文\n"
        "1. 纯数字\n正文\n"
        "Chapter 7 English\nbody\n"
        "楔子 开场\n正文\n"
        "番外 一\n正文\n"
        "后来他走了。\n"
        "完蛋了这件事。\n"
        "Cats are nice.\n"
        "2024年发生了很多事\n"
        "第 8 章 中间有空格\n正文\n"
        "第9章标题后面直接接正文这是很长的正文内容超过三十个字符用来测试间隙切分\n"
    )

    def test_the_one_pass_scorer_agrees_with_the_original_rule_by_rule(self) -> None:
        """Rule by rule, on text built to attack the line-start filter."""
        pool = [C.ChapterRule("default", C.DEFAULT_CHAPTER_RE), *C.CHAPTER_RULES]
        for rule in pool:
            with self.subTest(rule=rule.id):
                slow = C._score_pattern_slow(self.TRICKY, rule)
                fast = C.score_rules(self.TRICKY, (rule,)).get(rule.id)
                self.assertEqual(slow, fast)

    def test_the_one_pass_scorer_agrees_on_real_books(self) -> None:
        """On the golden books too, not just synthetic text.

        Skips when none of the books are on this machine, exactly like TestRealBooks:
        the golden file stores hashes, never book text.
        """
        pool = [C.ChapterRule("default", C.DEFAULT_CHAPTER_RE), *C.CHAPTER_RULES]
        checked = 0
        for book in self.golden.get("books") or []:
            if not os.path.isfile(book["path"]):
                continue
            checked += 1
            with open(book["path"], "rb") as fh:
                text = E.decode_txt(fh.read()).text
            text = text.replace("\r\n", "\n").replace("\r", "\n")
            with self.subTest(book=book["name"]):
                for rule in pool:
                    self.assertEqual(
                        C._score_pattern_slow(text, rule),
                        C.score_rules(text, (rule,)).get(rule.id),
                        f"{book['name']} / {rule.id}",
                    )
                # And the whole-pool decision the fast path now makes in one pass.
                slow = [
                    s for s in (C._score_pattern_slow(text, r) for r in pool) if s
                ]
                usable = [s for s in slow if s["shortRatio"] >= 0.5]
                usable.sort(key=lambda s: (-s["count"], -s["shortRatio"]))
                expected = usable[0]["id"] if usable else None
                got = (C.detect_chapter_re(text) or {}).get("id")
                self.assertEqual(got, expected, f"{book['name']}: detect picked differently")
        if checked == 0:
            self.skipTest("none of the golden books are present on this machine")

    def test_an_unanchored_rule_falls_back_to_the_slow_path(self) -> None:
        """A hand-written pattern may match mid-line, which a line-start scan cannot
        see. That is why the fallback exists, and this proves it is taken."""
        text = "正文里提到第一章 开端 的地方\n换行\n"
        rule = C.ChapterRule("loose", r"第[0-9一二三四五六七八九十]+章")
        self.assertEqual(
            C.score_rules(text, (rule,)).get("loose"),
            C._score_pattern_slow(text, rule),
        )

    def test_a_mixed_pool_scores_every_rule_the_slow_way(self) -> None:
        """One unanchored rule must not make the anchored ones report different numbers."""
        anchored = C.CHAPTER_RULES[0]
        loose = C.ChapterRule("loose", r"第[0-9]+章")
        got = C.score_rules(self.TRICKY, (anchored, loose))
        for rule in (anchored, loose):
            self.assertEqual(got.get(rule.id), C._score_pattern_slow(self.TRICKY, rule))

    def test_the_mark_guard_cap_is_unchanged(self) -> None:
        """_MARK_GUARD stops a pathological pattern from eating the whole book. The
        one-pass version must cap each rule identically to finditer()'s early break."""
        text = "".join(f"第{i}章 标题{i}\n正文\n" for i in range(1, 600))
        rule = C.CHAPTER_RULES[0]
        self.assertEqual(C.score_rules(text, (rule,))[rule.id], C._score_pattern_slow(text, rule))

    def test_scoring_a_sample_gives_the_same_answer_as_scoring_everything(self) -> None:
        """`_sample_bytes` is only allowed to save memory, not to change the verdict."""
        # Long enough to be truncated by _sample_bytes, and heavily CJK.
        text = "".join(f"第{i}章 标题{i}\n这是一段正文内容。\n" for i in range(1, 30000))
        data = text.encode("gb18030")
        self.assertGreater(len(data), E._SAMPLE_BYTES, "test needs a file bigger than the sample")
        sampled = E._sample_bytes(data)
        self.assertLess(len(sampled), len(data))
        self.assertEqual(len(sampled) % 4, 0, "alignment is what keeps UTF-32 samples intact")
        # Same score, so the same encoding verdict.
        self.assertEqual(E._score(sampled.decode("gb18030", "replace")),
                         E._score(data.decode("gb18030", "replace")))
        self.assertEqual(E.decode_txt(data).encoding, E.decode_txt(data[:E._SAMPLE_BYTES]).encoding)

    def test_chunked_decoding_is_identical_to_a_single_decode(self) -> None:
        """Including the cases chunking could plausibly break: a multi-byte character
        straddling a chunk boundary, invalid bytes, and a truncated tail.

        `_DECODE_CHUNK` is patched down instead of building 4 MB fixtures: a tiny,
        deliberately odd chunk size cuts through multi-byte sequences far more often
        than the real 4 MB size ever would, and it keeps the test instant. Asserting
        on the assertion would be worthless here - an unequal chunk boundary is the
        whole risk.
        """
        cases = {
            "utf-8 汉字": ("第1章 中文正文\n" * 200).encode("utf-8"),
            "gb18030 汉字": ("第1章 中文正文\n" * 200).encode("gb18030"),
            "utf-16-le 汉字": ("第1章 中文正文\n" * 200).encode("utf-16-le"),
            "utf-16-be 汉字": ("第1章 中文正文\n" * 200).encode("utf-16-be"),
            "utf-32-le 汉字": ("第1章 中文\n" * 100).encode("utf-32-le"),
            "非法字节": b"\xe4\xb8\xad" * 200 + b"\xff\xfe" + b"\xe4\xb8\xad" * 200,
            "截断末尾": b"\xe4\xb8\xad" * 200 + b"\xe4\xb8",
            "孤立代理": b"ok\xed\xa0\x80ok",
        }
        for name, data in cases.items():
            for enc in ("utf-8", "gb18030", "utf-16-le"):
                for chunk in (1, 3, 7, 64):
                    with self.subTest(case=name, enc=enc, chunk=chunk):
                        with mock.patch.object(E, "_DECODE_CHUNK", chunk):
                            self.assertEqual(
                                E._decode(data, enc, "replace"),
                                data.decode(enc, errors="replace"),
                            )

    def test_the_chunked_path_is_actually_taken(self) -> None:
        """Guard against the optimisation silently becoming dead code - which is
        exactly what happened on the first attempt: the strict-UTF-8 fast path called
        data.decode() directly and kept the whole 3.0x memory peak."""
        big = ("第1章 甲\n" * 3000).encode("utf-8")
        with mock.patch.object(E, "_DECODE_CHUNK", 64):
            self.assertGreater(len(big), 64, "input must exceed the patched chunk")
            self.assertEqual(E._decode(big, "utf-8", "replace"), big.decode("utf-8", "replace"))
        # The helper must really use an incremental decoder...
        self.assertIn("getincrementaldecoder", inspect.getsource(E._decode))
        # ...and the strict path every UTF-8 book takes must route through it.
        self.assertIn('_decode(data, "utf-8", "strict")', inspect.getsource(E.decode_txt))
        self.assertNotIn(
            'data.decode("utf-8", errors="strict")',
            inspect.getsource(E.decode_txt),
            "the single-shot decode is back, and with it the 3.0x peak",
        )
        self.assertEqual(E.decode_txt(big).encoding, "utf-8")

    def test_opening_a_big_book_does_not_decode_every_candidate_in_full(self) -> None:
        """The candidate scorer must decode a sample, not the whole file per candidate.

        Before this, every candidate was decoded in full and kept alive until the sort.
        Measured on a 5.6 MB GB18030 file: 6.49x the file size in peak memory. Scoring a
        512 KB sample and decoding only the winner brought that to 2.74x, with an
        identical verdict. The threshold sits between the two with margin on both sides,
        and the same file is decoded twice - old style and new - so this cannot pass by
        accident if the code silently reverts.
        """
        text = "".join(f"第{i}章 标题{i}\n这是一段正文内容，用来压测。\n" for i in range(1, 120000))
        data = text.encode("gb18030")
        size_mb = len(data) / 1024 / 1024
        self.assertGreater(size_mb, 4.0, "needs a file big enough for the ratio to mean something")

        def old_style(data: bytes):
            """The pre-optimisation loop, kept here as the control."""
            scored = []
            for enc, label in E._candidates(data):
                try:
                    t = data.decode(enc, errors="replace")
                except (UnicodeDecodeError, LookupError):
                    continue
                scored.append((E._score(t), enc, label, t))
            scored.sort(key=lambda row: row[0], reverse=True)
            return scored[0]

        def peak_ratio(fn) -> tuple[object, float]:
            gc.collect()
            tracemalloc.start()
            out = fn()
            _cur, peak = tracemalloc.get_traced_memory()
            tracemalloc.stop()
            return out, peak / 1024 / 1024 / size_mb

        new, new_ratio = peak_ratio(lambda: E.decode_txt(data))
        old, old_ratio = peak_ratio(lambda: old_style(data))

        # Same answer, very different memory - that is the whole claim.
        self.assertEqual(new.encoding, old[1])
        self.assertLess(new_ratio, 4.0, f"new path is {new_ratio:.2f}x the file ({size_mb:.1f} MB)")
        self.assertGreater(old_ratio, 4.0, f"the control should be worse than 4x, got {old_ratio:.2f}x")


